import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptRoot = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(scriptRoot, "..");
const repoRoot = path.resolve(frontendRoot, "..");
const artifactRoot = path.join(repoRoot, "acord-artifacts");

function readJson(fileName) {
  return JSON.parse(fs.readFileSync(path.join(artifactRoot, fileName), "utf8").replace(/^\uFEFF/, ""));
}

const truth = readJson("authoritative-semantic-truth-rp9.json");
const lineage = readJson("rp9-ontology-lineage.json");
const bundles = readJson("rp9-category-bundles.json");
const checks = {
  stagingActive: truth.status === "staging-active-semantic-baseline" && truth.activation?.state === "staging-active" && truth.activation?.scope === "staging",
  lineageActive: lineage.status === "staging-active" && lineage.activation?.state === "staging-active" && lineage.activation?.currentProductionBaseline === "RP-8",
  truthLinked: lineage.artifacts?.authoritativeSemanticTruth?.payloadSha256 === truth.integrity?.payloadSha256,
  bundlesLinked: lineage.artifacts?.categoryBundles?.payloadSha256 === bundles.integrity?.payloadSha256 && bundles.semanticTruthPayloadSha256 === truth.integrity?.payloadSha256,
  ontologyHashAligned: truth.canonicalOntology?.hash === lineage.ontologyHash && lineage.ontologyHash === bundles.ontologyHash,
  productionNotPromoted: truth.activation?.productionBaselineChanged === false && lineage.activation?.productionPromoted === false,
};
const failed = Object.entries(checks).filter(([, passed]) => !passed).map(([name]) => name);
if (failed.length) throw new Error(`RP-9 staging build validation failed: ${failed.join(", ")}`);

const manifest = {
  schemaVersion: "rp9-designer-build-manifest.v1",
  generatedAt: new Date().toISOString(),
  restorePoint: "RP-9",
  activationState: truth.activation.state,
  activationScope: truth.activation.scope,
  productionBaseline: "RP-8",
  semanticTruthPayloadSha256: truth.integrity.payloadSha256,
  ontologyLineagePayloadSha256: lineage.integrity.payloadSha256,
  categoryBundlesPayloadSha256: bundles.integrity.payloadSha256,
  ontologyHash: truth.canonicalOntology.hash,
  activeOntology: lineage.activeOntology,
  mappingContractVersion: "rp9.mapping.v1",
  nodeCount: Object.keys(truth.canonicalOntology.nodes).length,
  roleSafeRepresentationEquivalenceCount: truth.roleSafeEquivalences.length,
  multiInstanceFamilies: truth.multiInstanceFamilies,
  categoryBundles: {
    groups: bundles.groups.map((bundle) => ({ id: bundle.bundleId, conceptCount: bundle.nodeCount, nodeIds: bundle.nodeIds })),
    sections: bundles.sections.map((bundle) => ({ id: bundle.bundleId, conceptCount: bundle.nodeCount, nodeIds: bundle.nodeIds })),
  },
  checks,
};
const outputPath = path.join(frontendRoot, "src", "generated", "rp9BuildManifest.ts");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `// Generated by frontend/scripts/fetch-rp9-build-artifacts.mjs\nexport const rp9BuildManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`, "utf8");
process.stdout.write(`${JSON.stringify({ outputPath, ...manifest }, null, 2)}\n`);
