import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptRoot = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(scriptRoot, "..");
const repoRoot = path.resolve(frontendRoot, "..");
const baseUrl = String(
  process.env.RP8_ARTIFACT_BASE_URL ||
    "https://inchanted-api-production.greenriver-7266e28c.eastus.azurecontainerapps.io",
).replace(/\/+$/, "");
const mappingContractVersion = "rp8.mapping.v1";

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8").replace(/^\uFEFF/, ""));
}

async function fetchJson(endpoint) {
  const response = await fetch(`${baseUrl}${endpoint}`, {
    headers: { Accept: "application/json", "Cache-Control": "no-cache" },
    cache: "no-store",
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${endpoint}: HTTP ${response.status}`);
  }
  const contentType = response.headers.get("content-type") || "";
  if (!contentType.includes("application/json")) {
    throw new Error(`${endpoint} did not return JSON: ${contentType || "unknown"}`);
  }
  return response.json();
}

function collectCategoryBundles(ontology) {
  const groups = new Map();
  const sections = new Map();
  for (const node of Object.values(ontology.canonicalOntology?.nodes || {})) {
    for (const group of node.groups || []) {
      groups.set(group, (groups.get(group) || 0) + 1);
    }
    for (const section of node.sections || []) {
      sections.set(section, (sections.get(section) || 0) + 1);
    }
  }
  const entries = (source) => Array.from(source.entries())
    .map(([id, conceptCount]) => ({ id, conceptCount }))
    .sort((left, right) => left.id.localeCompare(right.id));
  return { groups: entries(groups), sections: entries(sections) };
}

const localTruth = readJson(path.join(repoRoot, "acord-artifacts", "authoritative-semantic-truth-rp8.json"));
const localLineage = readJson(path.join(repoRoot, "acord-artifacts", "rp8-ontology-lineage.json"));
const localOntology = readJson(path.join(repoRoot, "acord-artifacts", "ontology-phase31.json"));
const [remoteTruth, remoteLineage] = await Promise.all([
  fetchJson("/semantic-truth/current"),
  fetchJson("/ontology-lineage/current"),
]);

const checks = {
  truthRestorePoint: remoteTruth.restorePoint === "RP-8",
  truthActive: remoteTruth.status === "active-production-baseline" && remoteTruth.activation?.state === "active",
  truthHashMatchesLocal: remoteTruth.integrity?.payloadSha256 === localTruth.integrity?.payloadSha256,
  lineageRestorePoint: remoteLineage.restorePoint === "RP-8",
  lineageActiveOntology: remoteLineage.activeOntology === "phase33-strict-role-boundary-readiness",
  lineageHashMatchesLocal: remoteLineage.integrity?.payloadSha256 === localLineage.integrity?.payloadSha256,
  localRoleSafeEquivalencePresent:
    (localTruth.evidence?.roleSafeRepresentationEquivalences || []).length > 0,
};
const failedChecks = Object.entries(checks)
  .filter(([, passed]) => !passed)
  .map(([name]) => name);
if (failedChecks.length > 0) {
  throw new Error(`RP-8 build artifact validation failed: ${failedChecks.join(", ")}`);
}

const manifest = {
  schemaVersion: "rp8-designer-build-manifest.v1",
  generatedAt: new Date().toISOString(),
  sourceBaseUrl: baseUrl,
  productionBackendApi: baseUrl,
  restorePoint: remoteTruth.restorePoint,
  semanticTruthStatus: remoteTruth.status,
  semanticTruthActivation: remoteTruth.activation.state,
  semanticTruthPayloadSha256: remoteTruth.integrity.payloadSha256,
  ontologyLineagePayloadSha256: remoteLineage.integrity.payloadSha256,
  activeOntology: remoteLineage.activeOntology,
  canonicalOntology: remoteLineage.canonicalOntology,
  stabilizationPhase: remoteLineage.stabilizationPhase,
  mappingContractVersion,
  categoryBundles: collectCategoryBundles(localOntology),
  roleSafeRepresentationEquivalenceCount:
    localTruth.evidence.roleSafeRepresentationEquivalences.length,
  checks,
};

const outputPath = path.join(frontendRoot, "src", "generated", "rp8BuildManifest.ts");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by frontend/scripts/fetch-rp8-build-artifacts.mjs\nexport const rp8BuildManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`,
  "utf8",
);
process.stdout.write(`${JSON.stringify({ outputPath, ...manifest }, null, 2)}\n`);
